// Collects every page's <CoverImage> scene into IMAGE_PROMPTS.md, ready to paste into an image generator.
// The scene text lives in the page itself (it is also shown behind the cover's lightbulb button),
// so edit it there and re-run this script.
//
// Usage: node scripts/image-prompts.mjs
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'src')
const SECTIONS = [
  ['getting-started', 'Getting Started'],
  ['general', 'General Principles'],
  ['solid', 'SOLID'],
  ['pragmatic', 'Pragmatic & Clean Code'],
  ['architecture', 'Software Architecture'],
  ['testing', 'Testing & Quality'],
  ['laws', 'Laws & Aphorisms'],
]

// Appended to every scene so the whole series reads as one set
const STYLE =
  'Style: soft, high-quality 3D render with a playful claymation feel, rounded friendly shapes, ' +
  'warm amber and orange accent lighting against a deep charcoal-brown background, gentle rim light, ' +
  'shallow depth of field, clean uncluttered composition with the subject centred. ' +
  'No text, letters, numbers or logos anywhere in the image. Aspect ratio 16:10, 1360x850.'

const pages = fs
  .readdirSync(SRC, { recursive: true })
  .map((f) => f.replace(/\\/g, '/'))
  .filter((f) => f.endsWith('.md') && !f.startsWith('uz/'))
  .flatMap((file) => {
    const md = fs.readFileSync(path.join(SRC, file), 'utf8')
    const cover = md.match(/<CoverImage\s+src="\/covers\/([^"]+)\.webp"[^>]*>\s*<h1>(.*?)<\/h1>\s*<p>([\s\S]*?)<\/p>/)
    if (!cover) return []
    const [, image, title, scene] = cover
    return [{ url: '/' + file.replace(/(index)?\.md$/, ''), image, section: image.split('/')[0], title, scene: scene.trim() }]
  })

const exists = (image) => fs.existsSync(path.join(ROOT, 'public', 'covers', `${image}.webp`))
const done = pages.filter((p) => exists(p.image)).length

let out = `# Cover image prompts

<!-- Generated by scripts/image-prompts.mjs. Edit the scene in the page's <CoverImage>, then re-run. -->

${pages.length} pages, ${done} with a generated cover. Until a page has its own image, the site shows
\`public/placeholders/cover.webp\` (and \`card.webp\` on cards), so nothing breaks while you work through the list.

## Workflow

1. Paste the prompt below into your image generator (each one already includes the shared style).
2. Save the result as a PNG at the path shown, e.g. \`public/covers/general/kiss.png\`.
3. Run \`bun run images\`. It writes the \`.webp\` the site uses, plus a 1200x630 social preview in \`public/og/\`.
4. Delete the PNG and commit the \`.webp\` and \`.jpg\`. The page and every card that links to it pick the image up automatically.

Every scene stars the same tiny white robot used on Design Patterns, so the two sites look like siblings.

## Shared style

> ${STYLE}
`

for (const [key, heading] of SECTIONS) {
  const items = pages.filter((p) => p.section === key)
  if (!items.length) continue
  out += `\n## ${heading}\n`
  for (const p of items) {
    out += `\n### ${exists(p.image) ? '✅' : '⬜'} ${p.title}\n\n`
    out += `Page: \`${p.url}\` · Save as: \`public/covers/${p.image}.png\`\n\n`
    out += '```text\n' + `${p.scene}\n\n${STYLE}\n` + '```\n'
  }
}

fs.writeFileSync(path.join(ROOT, 'IMAGE_PROMPTS.md'), out)
console.log(`IMAGE_PROMPTS.md: ${pages.length} prompts, ${done} done`)
