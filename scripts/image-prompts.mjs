// Collects every page's cover scene (<CoverImage>) and card scene (`cardPrompt` frontmatter) into
// IMAGE_PROMPTS.md, ready to paste into an image generator. The scenes live in the pages themselves
// (the cover scene is also shown behind the cover's lightbulb button), so edit them there and re-run.
//
// Usage: node scripts/image-prompts.mjs
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'src')
const SECTIONS = [
  ['getting-started', 'Getting Started'],
  ['general', 'General Principles'],
  ['solid', 'SOLID'],
  ['pragmatic', 'Pragmatic & Clean Code'],
  ['architecture', 'Software Architecture'],
  ['testing', 'Testing & Quality'],
  ['laws', 'Laws & Aphorisms'],
]

// Shared look, so the whole series reads as one set
const LOOK =
  'Soft, high-quality 3D render with a playful claymation feel, rounded friendly shapes, ' +
  'glowing violet and purple accent lighting against a deep charcoal-indigo background, gentle rim light. ' +
  'No text, letters, numbers or logos anywhere in the image.'

// Sizes match the frames on the site; scripts/optimize-images.py centre-crops to them exactly
const COVER_STYLE = `Style: ${LOOK} Shallow depth of field, clean composition with the subject centred and room around it. Landscape 16:10, 1360x850 px.`
const CARD_STYLE = `Style: ${LOOK} A single bold subject filling most of the frame, simple uncluttered background, strong silhouette that stays readable as a small thumbnail. Landscape 16:10, 1024x640 px.`

const pages = fs
  .readdirSync(SRC, { recursive: true })
  .map((f) => f.split(path.sep).join('/'))
  .filter((f) => f.endsWith('.md') && !f.startsWith('uz/'))
  .flatMap((file) => {
    const md = fs.readFileSync(path.join(SRC, file), 'utf8')
    const cover = md.match(/<CoverImage\s+src="\/covers\/([^"]+)\.webp"[^>]*>\s*<h1>(.*?)<\/h1>\s*<p>([\s\S]*?)<\/p>/)
    if (!cover) return []
    const [, image, title, scene] = cover
    const card = md.match(/^cardPrompt:\s*(.+?)\s*$/m)?.[1]
    return [{
      url: '/' + file.replace(/(index)?\.md$/, ''),
      image,
      section: image.split('/')[0],
      title,
      scene: scene.trim(),
      card: card ? JSON.parse(card) : null,
    }]
  })

const exists = (dir, image) => fs.existsSync(path.join(ROOT, 'public', dir, `${image}.webp`))
const covers = pages.filter((p) => exists('covers', p.image)).length
const cards = pages.filter((p) => exists('cards', p.image)).length

let out = `# Image prompts

<!-- Generated by scripts/image-prompts.mjs. Edit the scenes in the pages (the <CoverImage> text and the
     \`cardPrompt\` frontmatter), then re-run \`bun run prompts\`. -->

Every page needs two images:

| Image | Where it shows | Size | Save as |
| --- | --- | --- | --- |
| **Cover** | Top of the page, under the title | 1360x850 px (16:10) | \`public/covers/<section>/<page>.png\` |
| **Card** | Cards on the overview pages that link to it | 1024x640 px (16:10) | \`public/cards/<section>/<page>.png\` |

Progress: ${covers}/${pages.length} covers, ${cards}/${pages.length} cards. Until an image exists, the site shows
\`public/placeholders/cover.webp\` or \`public/placeholders/card.webp\`, so nothing breaks while you work through the list.

## Workflow

1. Paste a prompt below into your image generator. Each one already includes the shared style and the size.
2. Save the result as a PNG at the path shown. A slightly different size is fine: the next step crops it.
3. Run \`bun run images\`. It centre-crops each PNG to its exact size and writes the \`.webp\` the site uses, plus
   a 1200x630 social preview in \`public/og/\` for covers.
4. Delete the PNGs and commit the \`.webp\` and \`.jpg\` files. The pages pick them up automatically.

Every scene stars the same tiny white robot used on Design Patterns, so the two sites look like siblings.

## Shared styles

**Cover:** ${COVER_STYLE}

**Card:** ${CARD_STYLE}
`

for (const [key, heading] of SECTIONS) {
  const items = pages.filter((p) => p.section === key)
  if (!items.length) continue
  out += `\n## ${heading}\n`
  for (const p of items) {
    out += `\n### ${p.title}\n\nPage: \`${p.url}\`\n\n`
    out += `${exists('covers', p.image) ? '✅' : '⬜'} **Cover**, 1360x850, save as \`public/covers/${p.image}.png\`\n\n`
    out += '```text\n' + `${p.scene}\n\n${COVER_STYLE}\n` + '```\n'
    if (p.card) {
      out += `\n${exists('cards', p.image) ? '✅' : '⬜'} **Card**, 1024x640, save as \`public/cards/${p.image}.png\`\n\n`
      out += '```text\n' + `${p.card}\n\n${CARD_STYLE}\n` + '```\n'
    }
  }
}

fs.writeFileSync(path.join(ROOT, 'IMAGE_PROMPTS.md'), out)
console.log(`IMAGE_PROMPTS.md: ${pages.length} pages, ${covers} covers and ${cards} cards done`)
